/// Dịch một câu theo ngôn ngữ đang chọn; `{0}`, `{1}` được thay bằng tham số.
func tr(_ key: String, _ args: Any...) -> String {
    var s = key
    if L10n.isEnglish, let t = L10n.en[key] { s = t }
    for (i, a) in args.enumerated() { s = s.replacingOccurrences(of: "{\(i)}", with: "\(a)") }
    return s
}

/// Lưu lựa chọn ngôn ngữ và làm mới giao diện khi đổi.
final class LangStore: ObservableObject {
    @Published var code: String {
        didSet { UserDefaults.standard.set(code, forKey: "lang") }
    }
    init() { code = UserDefaults.standard.string(forKey: "lang") == "en" ? "en" : "vi" }
}
